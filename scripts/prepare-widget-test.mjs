/**
 * Writes fixtures/widget-test/config.local.js from the demo seeder output.
 * Run after: pnpm seed:demo
 *
 *   node scripts/prepare-widget-test.mjs
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const livePath = join(root, "fixtures/quickstart-demo-account.live.json");
const outPath = join(root, "fixtures/widget-test/config.local.js");

if (!existsSync(livePath)) {
  console.error(
    "Missing fixtures/quickstart-demo-account.live.json — run `pnpm seed:demo` first (with stack up).",
  );
  process.exit(1);
}

const live = JSON.parse(readFileSync(livePath, "utf8"));
const pk = live.publishable_key?.publishable_key;
const agentId = live.agent_id;
const workspaceId = live.workspace_id;

if (!pk?.startsWith("pk_live_") || !agentId) {
  console.error("Live fixture is missing publishable_key or agent_id. Re-run pnpm seed:demo.");
  process.exit(1);
}

const config = {
  gatewayUrl: (process.env.GATEWAY_URL || "http://127.0.0.1:3000").replace(/\/$/, ""),
  widgetScriptUrl: (process.env.WIDGET_SCRIPT_URL || "http://127.0.0.1:3015/quickstart-widget.js").replace(
    /\/$/,
    "",
  ),
  publishableKey: pk,
  agentId,
  workspaceId,
  staffInboxUrl: workspaceId
    ? `http://127.0.0.1:3015/workspaces/${workspaceId}/inbox`
    : "http://127.0.0.1:3015/login",
  title: "QuickStart support",
  color: "#f15a24",
};

const body = `// Generated by scripts/prepare-widget-test.mjs — do not commit (gitignored)
window.QS_WIDGET_CONFIG = ${JSON.stringify(config, null, 2)};
`;

writeFileSync(outPath, body, "utf8");
console.log("Wrote", outPath);
console.log("Open http://127.0.0.1:8080/ (serve fixtures/widget-test with: pnpm widget:test:serve)");
